/* ---------- i18n ---------- */
const SUPPORTED = ["en", "ja", "zh"];
const STORAGE_KEY = "arcset-language";
const HTML_KEYS = new Set(["heroSub", "companyAddress"]);

function detectLanguage() {
  try { const s = localStorage.getItem(STORAGE_KEY); if (SUPPORTED.includes(s)) return s; } catch (e) {}
  for (const tag of navigator.languages || [navigator.language || "en"]) {
    const base = String(tag).toLowerCase().split("-")[0];
    if (SUPPORTED.includes(base)) return base;
  }
  return "en";
}

function splitWords(el) {
  const lang = document.documentElement.lang;
  const text = el.textContent.trim();
  const parts = lang === "en" ? text.split(/(\s+)/) : text.split(/(?<=[、。，．！？])/);
  el.textContent = "";
  let i = 0;
  parts.forEach((part) => {
    if (!part) return;
    if (lang === "en" && /^\s+$/.test(part)) { el.appendChild(document.createTextNode(" ")); return; }
    const span = document.createElement("span");
    span.className = "w"; span.textContent = part; span.style.setProperty("--i", i++);
    el.appendChild(span);
  });
}

function applyLanguage(lang) {
  const dict = translations[lang] || translations.en;
  document.documentElement.lang = lang === "zh" ? "zh-Hans" : lang;
  document.title = dict.pageTitle;
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", dict.pageDescription);
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] === undefined) return;
    if (HTML_KEYS.has(key)) el.innerHTML = dict[key]; else el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.querySelectorAll(".language-switcher button").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.language === lang)));
  document.querySelectorAll("[data-split]").forEach(splitWords);
  try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
}

document.querySelectorAll(".language-switcher button").forEach((b) => {
  b.addEventListener("click", () => {
    document.body.classList.remove("is-ready");
    applyLanguage(b.dataset.language);
    requestAnimationFrame(() => requestAnimationFrame(() => document.body.classList.add("is-ready")));
  });
});
